package academy.javaengineering.modern.switchexpressions;

/**
 * Practice exercises for Switch Expressions.
 */
public class SwitchExpressionsPractice {

    /*
     * Exercise 1: Roman Numeral Converter
     * 
     * Create a method that converts integers 1-10 to Roman numerals
     * using switch expressions with arrow syntax
     */

    /*
     * Exercise 2: Temperature Converter
     * 
     * Create a method that converts temperatures between:
     * - Celsius to Fahrenheit
     * - Fahrenheit to Celsius
     * - Celsius to Kelvin
     * 
     * Use switch expressions with the conversion type as input
     */

    /*
     * Exercise 3: Day of Week Activities
     * 
     * Create a method that returns suggested activities based on day:
     * - Monday: "Start work week"
     * - Tuesday-Thursday: "Work days"
     * - Friday: "End of work week"
     * - Saturday: "Day off"
     * - Sunday: "Rest day"
     */

    /*
     * Exercise 4: Simple Calculator
     * 
     * Create a method that performs basic operations:
     * - Addition, Subtraction, Multiplication, Division
     * - Handle division by zero
     * - Return appropriate error messages
     */
}

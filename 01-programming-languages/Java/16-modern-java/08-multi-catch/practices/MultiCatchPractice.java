package academy.javaengineering.modern.multicatch;

/**
 * Practice exercises for Multi-catch.
 */
public class MultiCatchPractice {

    /*
     * Exercise 1: Create a Safe Parser
     * 
     * Create a method that:
     * - Parses a string to Integer
     * - Parses a string to Double
     * - Uses multi-catch for NumberFormatException and NullPointerException
     * - Returns a success/failure result
     */

    /*
     * Exercise 2: Create a File Processor
     * 
     * Create a method that:
     * - Reads a file
     * - Parses its content as JSON
     * - Validates the JSON structure
     * - Uses multi-catch for IOException, ParseException, and ValidationException
     */

    /*
     * Exercise 3: Create a Network Client
     * 
     * Create a method that:
     * - Connects to a server
     * - Sends a request
     * - Reads the response
     * - Uses multi-catch for IOException, TimeoutException, and AuthenticationException
     */

    /*
     * Exercise 4: Create a Data Transformer
     * 
     * Create a method that:
     * - Takes a list of strings
     * - Converts each to a number
     * - Applies transformations
     * - Uses multi-catch for various conversion errors
     */
}

package academy.javaengineering.modern;

/**
 * Practice exercises for modern Java features.
 */
public class PracticeExercises {

    /*
     * Exercise 1: Create a Record for a Book
     * 
     * Create a record called Book with:
     * - title (String)
     * - author (String) 
     * - price (double)
     * - year (int)
     * 
     * Add a method to check if the book is recent (published after 2020)
     */

    /*
     * Exercise 2: Pattern Matching with Sealed Classes
     * 
     * Create a sealed interface Animal with permits for:
     * - Dog (name, breed)
     * - Cat (name, indoor)
     * - Bird (name, canFly)
     * 
     * Write a method that returns a description string based on the animal type
     */

    /*
     * Exercise 3: Use var and Text Blocks
     * 
     * Create a method that:
     * - Uses var to declare variables with complex generic types
     * - Uses a text block to format a report
     * - Demonstrates type inference with collections
     */

    /*
     * Exercise 4: Switch Expressions
     * 
     * Create a method that takes a grade (A-F) and returns:
     * - "Excellent" for A
     * - "Good" for B
     * - "Average" for C
     * - "Below Average" for D
     * - "Failing" for F
     * 
     * Use switch expressions with arrow syntax
     */

    /*
     * Exercise 5: Multi-catch and instanceof Pattern Matching
     * 
     * Create a method that:
     * - Parses a string to an integer
     * - Uses multi-catch for NumberFormatException and IllegalArgumentException
     * - Uses instanceof pattern matching to check if an object is a specific type
     */
}

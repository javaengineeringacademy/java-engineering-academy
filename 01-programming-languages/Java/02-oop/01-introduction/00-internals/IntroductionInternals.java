package academy.javaengineering.oop.internals;

public class IntroductionInternals {

    public static void main(String[] args) {
        System.out.println("=== OOP Introduction Internals ===\n");

        // 1. What is OOP?
        System.out.println("--- What is OOP? ---");
        System.out.println("Object-Oriented Programming paradigm");
        System.out.println("Organizes code around objects, not functions");
        System.out.println("Real-world modeling approach");

        // 2. Four Pillars
        System.out.println("\n--- Four Pillars of OOP ---");
        System.out.println("1. Encapsulation: hiding internal state");
        System.out.println("2. Inheritance: reusing code from parent");
        System.out.println("3. Polymorphism: one interface, many forms");
        System.out.println("4. Abstraction: hiding complexity");

        // 3. Procedural vs OOP
        System.out.println("\n--- Procedural vs OOP ---");
        System.out.println("Procedural: functions + data");
        System.out.println("OOP: objects + methods");
        System.out.println("OOP: better for large, complex systems");

        // 4. Class and Object
        System.out.println("\n--- Class vs Object ---");
        System.out.println("Class: blueprint/template");
        System.out.println("Object: instance of class");
        System.out.println("Class defines behavior, object has state");
    }
}

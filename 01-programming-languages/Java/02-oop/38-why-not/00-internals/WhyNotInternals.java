package academy.javaengineering.oop.internals;

public class WhyNotInternals {

    public static void main(String[] args) {
        System.out.println("=== Why Not OOP Internals ===\n");

        // 1. OOP Limitations
        System.out.println("--- OOP Limitations ---");
        System.out.println("1. Complexity: can be over-engineered");
        System.out.println("2. Performance: overhead vs procedural");
        System.out.println("3. Memory: more objects = more memory");
        System.out.println("4. Learning curve: steep for beginners");

        // 2. When NOT to Use OOP
        System.out.println("\n--- When NOT to Use ---");
        System.out.println("1. Simple scripts");
        System.out.println("2. Performance-critical code");
        System.out.println("3. Small programs");
        System.out.println("4. Data processing pipelines");

        // 3. Alternatives
        System.out.println("\n--- Alternatives ---");
        System.out.println("1. Functional programming");
        System.out.println("2. Procedural programming");
        System.out.println("3. Data-oriented design");
        System.out.println("4. Hybrid approaches");

        // 4. Best Practices
        System.out.println("\n--- Best Practices ---");
        System.out.println("1. Use OOP for complex systems");
        System.out.println("2. Keep classes small and focused");
        System.out.println("3. Prefer composition over inheritance");
        System.out.println("4. Consider performance implications");
    }
}
